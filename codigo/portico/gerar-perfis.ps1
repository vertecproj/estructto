# retangulo de cantos arredondados: area e inercia em torno do eixo paralelo a b (mm2, mm4)
function Arr([double]$b, [double]$h, [double]$r) {
    $ac = $r * $r * (1 - [Math]::PI / 4)
    $A = $b * $h - 4 * $ac
    $I = $b * [Math]::Pow($h, 3) / 12 - 4 * (0.00755 * [Math]::Pow($r, 4) + $ac * [Math]::Pow($h / 2 - 0.2234 * $r, 2))
    , @($A, $I)
}
function Tubo([string]$fam, [double]$h, [double]$b, [double]$t) {
    $ro = 1.5 * $t; $ri = 0.5 * $t
    $e = Arr $b $h $ro; $i = Arr ($b - 2 * $t) ($h - 2 * $t) $ri
    $e2 = Arr $h $b $ro; $i2 = Arr ($h - 2 * $t) ($b - 2 * $t) $ri
    $A = ($e[0] - $i[0]) / 100; $Ix = ($e[1] - $i[1]) / 1e4; $Iy = ($e2[1] - $i2[1]) / 1e4
    $hs = $h.ToString('0.##', $br); $bs = $b.ToString('0.##', $br); $ts = $t.ToString('0.00', $br)
    $script:out.Add(('{0};{1}x{2};Tubo {1}x{2}x{3};TR;{4};{5};{6};{7};{7};{8};{9};{10}' -f $fam, $hs, $bs, $ts, (F ($A * 0.785) 2), (F $h 2), (F $b 2), (F $t 2), (F $A 3), (F $Ix 3), (F $Iy 3)))
}
